r"""Emit pgfplots coordinate data used by the manuscript figures.

Reads the analysis JSON produced by ``analyze_stats.py`` and
``defense_eval.py`` and writes self-contained pgfplots data snippets
(``fig_*.tex``) into ``experiment_validation/analysis/``. The manuscript
\input{}s these so figures are regenerated directly from the computed numbers
(no manual transcription, no binary image assets).
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ANALYSIS = ROOT / "experiment_validation" / "analysis"


def _short(model: str) -> str:
    return (model.replace("-Instruct", "").replace("-instruct", "")
            .replace("-Chat", "").replace("-it", ""))


def fig_phi_ci() -> None:
    stats = json.loads((ANALYSIS / "model_stats.json").read_text())
    stats = sorted(stats, key=lambda s: s["phi_mean"], reverse=True)
    coords, errs, ticks = [], [], []
    for i, s in enumerate(stats):
        coords.append(f"({i},{s['phi_mean']:.4f})")
        lo = s["phi_mean"] - s["phi_ci"][0]
        hi = s["phi_ci"][1] - s["phi_mean"]
        errs.append(f"({i},{s['phi_mean']:.4f}) +- ({hi:.4f},{lo:.4f})")
        ticks.append(f"{i}/{{{_short(s['model'])}}}")
    body = [
        "% Auto-generated by make_figures.py -- phi with 95% bootstrap CI",
        "\\pgfplotsset{width=\\linewidth,height=6cm,compat=1.16}",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  ybar, bar width=10pt, ymin=0, ymax=0.40,",
        "  ylabel={Mean semantic similarity $\\phi$},",
        "  xtick={" + ",".join(str(i) for i in range(len(stats))) + "},",
        "  xticklabels={" + ",".join("{" + _short(s['model']) + "}" for s in stats) + "},",
        "  x tick label style={rotate=40,anchor=east,font=\\scriptsize},",
        "  enlarge x limits=0.08, ymajorgrids, tick align=inside,",
        "]",
        "\\addplot+[ybar, fill=blue!35, draw=blue!60!black,",
        "  error bars/.cd, y dir=both, y explicit] coordinates {",
        "  " + " ".join(errs),
        "};",
        "\\end{axis}",
        "\\end{tikzpicture}",
    ]
    (ANALYSIS / "fig_phi_ci.tex").write_text("\n".join(body) + "\n", encoding="utf-8")


def fig_defense() -> None:
    path = ANALYSIS / "defense_eval.json"
    if not path.exists():
        print("[figures] defense_eval.json missing; skipping defense figure")
        return
    data = json.loads(path.read_text())
    models = []
    for s in data:
        if s["model"] not in models:
            models.append(s["model"])
    defenses = ["baseline", "bucket_8", "pad_fixed", "batch_2", "batch_4", "rand_pad_8"]
    lut = {(s["model"], s["defense"]): s for s in data}
    colors = ["black!55", "blue!45", "red!45", "green!45!black", "orange!60", "purple!45"]
    lines = [
        "% Auto-generated by make_figures.py -- residual phi per defense",
        "\\pgfplotsset{width=\\linewidth,height=6cm,compat=1.16}",
        "\\begin{tikzpicture}",
        "\\begin{axis}[",
        "  ybar, bar width=7pt, ymin=0,",
        "  ylabel={Residual $\\phi$ (mean, 95\\% CI)},",
        "  symbolic x coords={" + ",".join(m.replace("-Instruct", "") for m in models) + "},",
        "  xtick=data, x tick label style={font=\\scriptsize},",
        "  legend style={font=\\scriptsize,at={(0.5,1.03)},anchor=south,legend columns=3},",
        "  ymajorgrids, enlarge x limits=0.4,",
        "]",
    ]
    for d, c in zip(defenses, colors):
        coords = []
        for m in models:
            s = lut.get((m, d))
            if not s:
                continue
            lo = s["phi_mean"] - s["phi_ci"][0]
            hi = s["phi_ci"][1] - s["phi_mean"]
            coords.append(f"({m.replace('-Instruct','')},{s['phi_mean']:.4f}) +- ({hi:.4f},{lo:.4f})")
        lines.append(f"\\addplot+[ybar,fill={c},draw=black,")
        lines.append("  error bars/.cd, y dir=both, y explicit] coordinates {" + " ".join(coords) + "};")
        lines.append("\\addlegendentry{" + d.replace("_", "\\_") + "}")
    lines += ["\\end{axis}", "\\end{tikzpicture}"]
    (ANALYSIS / "fig_defense.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    fig_phi_ci()
    fig_defense()
    print("[figures] wrote fig_phi_ci.tex and (if available) fig_defense.tex")


if __name__ == "__main__":
    main()
